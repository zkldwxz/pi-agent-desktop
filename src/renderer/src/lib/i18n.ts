/**
 * UI language.
 *
 * The shell's own chrome ships in Chinese by default — this is a Chinese-
 * first product — while everything the agent writes (thinking, answers, tool
 * output) stays exactly as the model produced it. English is one toggle away
 * for anyone who prefers it.
 *
 * Keys are the English source strings, so an untranslated key degrades to
 * readable English instead of a missing-key placeholder.
 */

export type Locale = "zh" | "en";

const KEY = "pi-locale";

let locale: Locale = (() => {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "en" || saved === "zh") return saved;
  } catch {
    /* private mode, first run */
  }
  return "zh";
})();

const listeners = new Set<() => void>();

export function getLocale(): Locale {
  return locale;
}

/**
 * The BCP-47 tag for the interface language.
 *
 * `toLocaleDateString(undefined, …)` follows the *operating system*, so a
 * Chinese interface running on an English Windows box labels the usage axis
 * "Sep 3" while every word around it is Chinese. Anything that formats dates or
 * numbers for display passes this instead.
 */
export function localeTag(): string {
  return locale === "zh" ? "zh-CN" : "en-US";
}

export function setLocale(next: Locale): void {
  locale = next;
  try {
    localStorage.setItem(KEY, next);
  } catch {
    /* ignore */
  }
  listeners.forEach((listener) => listener());
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Re-renders the component when the language changes. */
export function useLocale(): Locale {
  return useSyncExternalStore(subscribe, getLocale, getLocale);
}

