/** Translate a UI string. Unknown strings fall through as English. */
export function t(text: string): string {
  if (locale === "en") return text;
  return ZH[text] ?? text;
}

/** Translate with `{name}` placeholders. */
export function tf(text: string, vars: Record<string, string | number>): string {
  const template = t(text);
  return template.replace(/\{(\w+)\}/g, (_match, key: string) => String(vars[key] ?? `{${key}}`));
}

/**
 * The label for an "Open with" row.
 *
 * The two rows that lead every list are ours, so they translate like any other
 * UI string. Everything under them is the operating system's own label for an
 * application — "Open in Total Commander", "在ZCode中打开" — and stays exactly
 * as registered, because translating it would misname the application.
 */
export function openerName(opener: AppOpener): string {
  /* the row always means the operating system's own file browser, and on macOS
     the honest label is the application's name rather than a translation of
     the Windows one */
  if (opener.kind === "reveal") return IS_MAC ? "Finder" : t("File manager");
  if (opener.kind === "default") return t("Default application");
  return opener.name;
}
